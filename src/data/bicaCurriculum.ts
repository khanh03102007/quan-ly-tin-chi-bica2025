export function getCourseKnowledgeBlock(course: { ma_hoc_phan?: string; ten_hoc_phan?: string }): string {
  if (!course.ma_hoc_phan && !course.ten_hoc_phan) return 'V. Khối kiến thức theo ngành';
  const cleanCode = (course.ma_hoc_phan || '').trim().toUpperCase();
  const cleanName = (course.ten_hoc_phan || '').trim().toLowerCase();

  // 1. Tìm chính xác trong BICA_CURRICULUM
  const found = BICA_CURRICULUM.find(
    (c) =>
      c.ma_hoc_phan.toUpperCase() === cleanCode ||
      (cleanName.length > 3 && c.ten_hoc_phan.trim().toLowerCase() === cleanName)
  );
  if (found) return found.khoi_kien_thuc;

  // 2. Nhận diện theo tiền tố mã học phần và từ khóa
  if (
    cleanCode.startsWith('PHI') ||
    cleanCode.startsWith('PEC') ||
    cleanCode.startsWith('POL') ||
    cleanCode.startsWith('HIS') ||
    cleanCode.startsWith('FLF') ||
    cleanCode.startsWith('PES') ||
    cleanName.includes('triết') ||
    cleanName.includes('tiếng anh') ||
    cleanName.includes('tiếng nhật') ||
    cleanName.includes('kinh tế chính trị') ||
    cleanName.includes('hồ chí minh') ||
    cleanName.includes('chủ nghĩa xã hội') ||
    cleanName.includes('quân sự') ||
    cleanName.includes('thể dục')
  ) {
    return 'I. Khối kiến thức chung';
  }

  if (
    cleanCode.startsWith('MAT') ||
    cleanCode.startsWith('PHY') ||
    cleanCode.startsWith('CHE') ||
    cleanName.includes('giải tích') ||
    cleanName.includes('đại số') ||
    cleanName.includes('vật lý') ||
    cleanName.includes('xác suất') ||
    cleanName.includes('hóa học')
  ) {
    return 'II.1 Khối học phần cơ bản theo lĩnh vực';
  }

  if (
    cleanCode.startsWith('VJU') ||
    cleanName.includes('thế kỷ 21') ||
    cleanName.includes('phát triển bền vững') ||
    cleanName.includes('khởi nghiệp') ||
    cleanName.includes('văn hóa nhật')
  ) {
    return 'II.2 Khối học phần thế kỷ 21';
  }

  if (
    cleanCode.startsWith('IT') ||
    cleanCode.startsWith('ELT') ||
    cleanCode.startsWith('MEC') ||
    cleanName.includes('lập trình') ||
    cleanName.includes('mạch điện') ||
    cleanName.includes('tin học cơ sở') ||
    cleanName.includes('cơ học')
  ) {
    return 'III. Khối kiến thức theo khối ngành';
  }

  if (
    cleanCode.startsWith('EMA') ||
    cleanName.includes('điều khiển tự động') ||
    cleanName.includes('mạch số') ||
    cleanName.includes('tín hiệu') ||
    cleanName.includes('điện tử công suất') ||
    cleanName.includes('máy điện')
  ) {
    return 'IV. Khối kiến thức theo nhóm ngành';
  }

  return 'V. Khối kiến thức theo ngành';
}

export interface BlockStatistic {
  block: KnowledgeBlockTarget;
  registeredCourses: any[];
  passedCourses: any[];
  inProgressCourses: any[];
  failedCourses: any[];
  totalRegisteredCredits: number;
  totalPassedCredits: number;
  totalInProgressCredits: number;
  targetCredits: number;
  completionPercent: number;
}

export function calculateKnowledgeBlockStats(courses: any[]): BlockStatistic[] {
  return BICA_BLOCK_TARGETS.map((target) => {
    const matched = (courses || []).filter((c) => getCourseKnowledgeBlock(c) === target.name);
    const passed = matched.filter((c) => c.ket_qua === 'Dat');
    const inProgress = matched.filter((c) => c.ket_qua === 'DangHoc');
    const failed = matched.filter((c) => c.ket_qua === 'KhongDat');

    const totalRegisteredCredits = matched.reduce((sum, c) => sum + (Number(c.so_tin_chi) || 0), 0);
    const totalPassedCredits = passed.reduce((sum, c) => sum + (Number(c.so_tin_chi) || 0), 0);
    const totalInProgressCredits = inProgress.reduce((sum, c) => sum + (Number(c.so_tin_chi) || 0), 0);

    const effectiveCredits = totalPassedCredits > 0 ? totalPassedCredits : totalRegisteredCredits;
    const completionPercent = Math.min(
      100,
      Math.round((effectiveCredits / target.targetCredits) * 100)
    );

    return {
      block: target,
      registeredCourses: matched,
      passedCourses: passed,
      inProgressCourses: inProgress,
      failedCourses: failed,
      totalRegisteredCredits,
      totalPassedCredits,
      totalInProgressCredits,
      targetCredits: target.targetCredits,
      completionPercent,
    };
  });
}

